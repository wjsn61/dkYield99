import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 앞 예제의 함수를 다시 씁니다
def calculate_yield(plant):
    """수율 = 전환율 × 선택도 × 분리회수율  (각 %, 그래서 10000으로 나눔)"""
    y = plant["전환율"] * plant["선택도"] * plant["분리회수율"] / 10000
    return round(min(100, max(0, y)), 1)      # 0~100 밖으로 안 나가게

base_state = {"전환율": 78, "선택도": 92, "분리회수율": 98}
baseline = calculate_yield(base_state)
print(f"기준값: {baseline}")

# %% [2] 하나씩 올려 보며 견줍니다
print(f"\n{'무엇을 +10':<14}{'결과':>10}{'변화':>10}")
print("-" * 36)
for key in base_state:
    changed = dict(base_state)          # ★ 매번 새로 복사 - 앞의 변경이 쌓이면 안 됩니다
    changed[key] = changed[key] + 10
    value = calculate_yield(changed)
    print(f"{key:<14}{value:>10.2f}{value - baseline:>+10.2f}")   # :+ 는 부호를 항상

# %% [3] 왜 매번 복사했나
