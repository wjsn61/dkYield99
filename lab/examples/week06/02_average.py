# %% [1] 5주에 한 것을 함수로
def average(numbers):
    """평균 = 모두 더해서 개수로 나눈다."""   # 함수 설명(독스트링)
    return sum(numbers) / len(numbers)


print(average([80, 78, 81, 77, 83]))
print(average([1, 2, 3]))

# ★ 이 함수를 기억해 두세요. 12주에 그대로 다시 씁니다.

# %% [2] 함수로 만들면 뭐가 좋나
score_groups = [[80, 90], [70, 75, 80], [100]]
for group in score_groups:
    print(group, "→", average(group))     # 몇 개든 같은 함수로

# %% [3] 빈 목록을 넣으면?
try:                                    # try : 에러가 날 수 있는 곳
    print(average([]))
except ZeroDivisionError as e:          # except : 그 에러가 나면 여기로
    print("에러:", e)
    print("→ 개수가 0이면 나눌 수 없습니다.")

# %% [4] 그런 경우까지 챙긴 함수
def average2(numbers):
    if not numbers:          # 빈 리스트는 '거짓' 으로 취급됩니다
        return 0
    return sum(numbers) / len(numbers)


print(average2([]))
print(average2([1, 2, 3]))


