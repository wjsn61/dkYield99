import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 가장 단순한 함수
def greet():             # def 이름( ) :  ← 콜론 잊지 마세요
    print("안녕하세요")  # 들여쓴 부분이 함수의 몸통


greet()                   # 부를 때는 이름( )
greet()                   # 몇 번이든

# %% [2] 값을 받아서 (매개변수)
def twice(x):             # x 는 받을 값에 붙인 이름
    return x * 2         # return : 결과를 돌려주기


print(twice(5))
print(twice(100))
result = twice(7)           # 돌려받은 값을 담을 수도 있습니다
print(result)

# %% [3] print 와 return 은 다릅니다
def print_only(x):
    print(x * 2)         # 화면에 찍고 끝. 돌려주는 값은 없음(None)


def give_back(x):
    return x * 2


a = print_only(5)
b = give_back(5)
print("a =", a)          # None
print("b =", b)          # 10  ← 이건 계속 쓸 수 있습니다

# %% [4] 여러 개를 받아서
def add(a, b):
    return a + b


print(add(3, 4))


