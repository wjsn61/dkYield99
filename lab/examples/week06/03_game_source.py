# %% [2] 그대로 옮겨 써 봅니다
def calculate_yield(plant):
    """수율 = 전환율 × 선택도 × 분리회수율  (각 %, 그래서 10000으로 나눔)"""
    y = plant["전환율"] * plant["선택도"] * plant["분리회수율"] / 10000
    return round(min(100, max(0, y)), 1)      # 0~100 밖으로 안 나가게

# %% [3] 실행
plant = {"전환율": 78, "선택도": 92, "분리회수율": 98}
print("수율 =", calculate_yield(plant))

# %% [4] 재료를 바꾸면
better_catalyst = dict(plant)                # dict( ) 로 복사 (3주)
better_catalyst["전환율"] = 88               # 78 → 88
print("전환율을 10 올리면 →", calculate_yield(better_catalyst))

better_recovery = dict(plant)
better_recovery["분리회수율"] = 99.5
print("분리회수율만 올리면 →", calculate_yield(better_recovery))


