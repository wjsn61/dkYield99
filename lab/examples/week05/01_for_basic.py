# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 리스트를 하나씩
values = [80, 78, 81, 77, 83]
for v in values:          # 값들에서 하나씩 꺼내 v 에 담고, 아래를 실행
    print(v)

# %% [2] 몇 번째인지도 함께 (enumerate)
for i, v in enumerate(values, start=1):   # start=1 : 1부터 세기
    print(f"{i}번째: {v}")

# %% [3] 정해진 횟수만큼 (range)
for i in range(5):       # 0,1,2,3,4  - 5는 포함되지 않습니다
    print("반복", i)

for i in range(1, 6):    # 1,2,3,4,5
    print(i, end=" ")    # end=" " : 줄을 바꾸지 말고 한 칸만 띄우기
print()                  # 줄바꿈

# %% [4] 반복 안에서 값을 모으기
doubled = []
for v in values:
    doubled.append(v * 2)   # .append( ) : 리스트 맨 뒤에 붙이기
print(doubled)


