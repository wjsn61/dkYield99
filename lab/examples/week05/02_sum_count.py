# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 하나씩 더해 봅니다
values = [80, 78, 81, 77, 83]

total = 0                 # 그릇을 0으로 비워 두고 시작
for v in values:
    total = total + v      # 지금까지의 합계에 v 를 더해 다시 담기
    print("지금까지:", total)

print("합계:", total)

# %% [2] 개수도 세어 봅니다
count = 0
for v in values:
    count = count + 1      # 값이 뭐든 하나 지날 때마다 +1
print("개수:", count)

# %% [3] 합계 ÷ 개수
print("합계 ÷ 개수 =", total / count)

# ★ 이 값에 이름이 있습니다. 12주에 다시 만납니다.
#   (아직 '통계' 라는 말은 쓰지 않습니다)

# %% [4] 파이썬이 이미 갖고 있는 것
print(sum(values))                    # sum( ) : 합계
print(len(values))                    # len( ) : 개수
print(sum(values) / len(values))

