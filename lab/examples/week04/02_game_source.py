# %% [1] 게임의 진짜 소스
#
#     ┌────────────────────────────────────────────────────────────┐
#     │ def enact_card(plant, card):
#     │     # 일회성 설비는 이미 설치했으면 다시 못 함
#     │     if card.get("일회성") and card["아이디"] in 설치한_아이디:
#     │         return False, "이미 설치되어 있습니다."
#     │
#     │     # 예산이 모자라면 시행 불가
#     │     if plant["예산"] < card["비용"]:
#     │         return False, "예산이 부족합니다."
#     │
#     │     # 여기까지 왔으면 시행 가능 → 돈을 쓴다
#     │     plant["예산"] = plant["예산"] - card["비용"]
#     └────────────────────────────────────────────────────────────┘
#
#  if 가 두 개 있습니다. 각각 무엇을 막는지 찾아보세요.
#  ※ 진짜 소스는 설비목록에서 아이디를 꺼내 쓰지만, 아래 [2]~[3] 에서는
#    아이디만 담은 목록으로 단순하게 두었습니다. 하는 일은 같습니다.

# %% [2] 딕셔너리 꺼내기가 섞여 있을 뿐, 하는 일은 1주의 뺄셈과 같습니다
plant = {"예산": 1000, "설비목록": ["heat_recovery"]}
card = {"아이디": "catalyst_v2", "이름": "고효율 촉매 도입", "비용": 250}

print("가진 돈  :", plant["예산"])
print("필요한 돈:", card["비용"])
print("이미 깔린 설비:", plant["설비목록"])

# %% [3] 조건을 하나씩 따져 봅니다 - 위 소스의 if 두 개 그대로입니다
if card["아이디"] in plant["설비목록"]:      # 4주 in - 안에 있나 묻기
    print("X  이미 설치되어 있습니다")
elif plant["예산"] < card["비용"]:
    print("X  예산이 부족합니다")
else:
    print("O  시행할 수 있습니다")

# ✏️ 해 보기
#    card["아이디"] 를 "heat_recovery" 로 바꾸면 어느 줄이 찍힐까요?

# %% [4] 값을 바꿔 가며
for money in (100, 250, 1000):
    plant["예산"] = money
    can_afford = plant["예산"] >= card["비용"]
    print(f"  예산 {money:>5}억  →  {'가능' if can_afford else '불가'}")


