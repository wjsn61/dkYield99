# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 가장 단순한 조건
#        if 뒤의 말이 '참' 일 때만 아래 들여쓴 줄이 실행됩니다.
budget = 300
if budget < 500:          # <  작다   >  크다   <= 작거나 같다
    print("예산이 부족합니다")     # ← 4칸 들여쓰기가 '이 안쪽' 이라는 표시

print("여기는 조건과 상관없이 항상 실행됩니다")

# %% [2] 아니면 (else)
budget = 800
if budget < 500:
    print("부족합니다")
else:
    print("시행할 수 있습니다")

# %% [3] 여러 갈래 (elif = else if)
score = 72
if score >= 80:
    print("좋음")
elif score >= 60:        # 위 조건이 거짓일 때만 따집니다
    print("보통")
else:
    print("나쁨")

# %% [4] 조건을 겹치기
budget, installed = 80, False   # 한 줄에 두 개를 담을 수도 있습니다
if budget >= 30 and not installed:      # and : 둘 다 참이어야
    print("시행 가능")
else:
    print("아직 안 됩니다")


