import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 재료
#      '일회성' 은 한 번 지으면 다시 못 짓는 설비라는 표시입니다.
#      운전 카드에는 이 이름표가 아예 없습니다 - 그래서 매달 다시 쓸 수 있어요.
plant = {"예산": 40, "설치한_아이디": ["heat_recovery"]}
cards = [
    {"아이디": "reactor_temp_up", "이름": "반응기 온도 상승",  "비용": 0},
    {"아이디": "heat_recovery",   "이름": "폐열 회수 장치",    "비용": 30, "일회성": True},
    {"아이디": "online_analyzer", "이름": "온라인 분석기 설치", "비용": 15, "일회성": True},
    {"아이디": "waste_water",     "이름": "폐수처리 설비 증설", "비용": 30, "일회성": True},
]

# %% [2] ✏️ 규칙을 그대로 옮겨 씁니다
for card in cards:
    # .get( ) 이라서 '일회성' 이 없는 운전 카드는 조용히 None → 이 if 를 지나갑니다
    if card.get("일회성") and card["아이디"] in plant["설치한_아이디"]:
        print(f'X  {card["이름"]} - 이미 설치됨')
    elif plant["예산"] < card["비용"]:
        print(f'X  {card["이름"]} - 예산 부족')
    else:
        plant["예산"] = plant["예산"] - card["비용"]
        plant["설치한_아이디"].append(card["아이디"])
        print(f'O  {card["이름"]} 시행 - 남은 예산 {plant["예산"]}억')

# %% [3] 순서를 바꾸면 결과가 달라집니다
plant = {"예산": 40, "설치한_아이디": []}
for card in reversed(cards):      # reversed( ) : 거꾸로
    installed = card.get("일회성") and card["아이디"] in plant["설치한_아이디"]
    if plant["예산"] >= card["비용"] and not installed:
        plant["예산"] -= card["비용"]      # -= 는 '빼서 다시 담기'
        plant["설치한_아이디"].append(card["아이디"])
        print(f'O  {card["이름"]}  남은 {plant["예산"]}')
    else:
        print(f'X  {card["이름"]}')


