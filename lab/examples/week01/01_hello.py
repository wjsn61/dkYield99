# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] print( ) - 괄호 안의 것을 화면에 찍어라
#        따옴표 " " 로 감싼 것을 '문자열' 이라고 합니다. 글자 덩어리라는 뜻입니다.
print("Hello, dkYield99!")

# %% [2] 쉼표로 여러 개를 한 줄에
#        쉼표로 나눠 넣으면 사이에 한 칸씩 띄어서 찍힙니다.
print("안녕하세요", "dkYield99", "입니다")

# %% [3] 따옴표가 없으면 '계산할 것' 으로 봅니다
print(1 + 1)          # 따옴표 없음 → 계산해서  2
print("1 + 1")        # 따옴표 있음 → 글자 그대로  1 + 1

# %% [4] 사칙연산 - 게임의 모든 계산이 이 다섯 개로 만들어집니다
print(7 + 3)          # +   더하기      → 10
print(7 - 3)          # -   빼기        → 4     (예산에서 비용을 뺄 때)
print(7 * 3)          # *   곱하기      → 21    (전환율 × 선택도)
print(7 / 3)          # /   나누기      → 2.333…  ★ 항상 소수로 나옵니다
print(7 // 3)         # //  몫만        → 2
print(7 % 3)          # %   나머지      → 1
print(7 ** 3)         # **  거듭제곱    → 343   (12주 표준편차에서 씁니다)

# %% [5] 섞어 쓰면 곱하기·나누기가 먼저입니다 (학교에서 배운 그대로)
print(2 + 3 * 4)      # → 14   (3*4 를 먼저)
print((2 + 3) * 4)    # → 20   (괄호가 우선)

# %% [6] 게임에 실제로 나오는 계산
print(1000 - 100)             # 예산 1000 에서 비용 100 을 쓰면
print(1000 * 0.75)            # 생산량 1000 톤 중 순도 75% 만큼
print(78 * 92 * 98 / 10000)   # 전환율×선택도×회수율 = 수율 (%)


