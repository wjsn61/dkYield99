# %% [1] = 는 '같다' 가 아니라 '넣어라' 입니다
budget = 1000
print(budget)           # 이름만 쓰면 담긴 값이 나옵니다

# %% [2] 값의 종류가 세 가지 있습니다 (자료형)
whole = 1000              # int   : 딱 떨어지는 수
decimal = 52.3              # float : 소수점이 있는 수
text = "dkYield99 1호"      # str   : 따옴표로 감싼 글자

print(whole, decimal, text)
print(type(whole), type(decimal), type(text))   # type( ) : 이게 무슨 종류냐고 묻기

# %% [3] 값은 바뀝니다 - 그래서 '변수'
budget = 1000
print("처음    :", budget)

budget = budget - 300        # 오른쪽을 먼저 계산해서 다시 예산에 담습니다
print("300 쓴 뒤:", budget)

# %% [4] 숫자와 글자는 그냥 섞이지 않습니다
print("예산은 " + str(budget) + "억")   # str( ) 로 숫자를 글자로 바꿔야 이어붙습니다
print(f"예산은 {budget}억")             # f"..." 안의 { } 는 값을 끼워 넣는 자리


