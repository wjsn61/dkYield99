import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 내 카드
mine = {
    "아이디": "my_first_card",
    "이름": "나의 첫 카드",
    "분류": "운전",
    "비용": 80,
    "즉시효과": {"수율": 6},
}

# %% [2] 붙여넣기 좋은 모양으로 찍기
print("    {")
for key, value in mine.items():
    if isinstance(value, str):                 # isinstance : 이게 그 종류인가
        print(f'        "{key}": "{value}",')
    else:
        print(f'        "{key}": {value},')
print("    },")

