# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 본보기 한 장 (게임 데이터에서 옮겨 온 것)
sample = {
    "아이디": "reactor_temp_up",
    "이름": "반응기 온도 상승",
    "비용": 100,
    "즉시효과": {"수율": 5},
}
for key, value in sample.items():
    print(f"{key:<10} {value}")

# %% [2] dict( ) 로 복사합니다
mine = dict(sample)               # 값을 통째로 베낀 '새' 딕셔너리
mine["아이디"] = "my_first_card"
mine["이름"] = "나의 첫 카드"
print("내것  :", mine["이름"])
print("본보기:", sample["이름"])   # 원본은 그대로

# %% [3] ★ dict( ) 없이 하면 - 같은 것을 두 이름으로 부르는 셈
alias = sample                    # 복사가 아니라 '같은 것에 이름 하나 더'
alias["이름"] = "망가뜨림"
print("그냥  :", alias["이름"])
print("본보기:", sample["이름"])   # ★ 원본까지 바뀌었습니다

# %% [4] 왜 그런가
print("""
= 은 '값을 베끼는 것' 이 아니라 '같은 것에 이름표를 하나 더 붙이는 것' 입니다.
숫자·글자는 바꿀 수 없어서 티가 안 나지만,
리스트·딕셔너리는 바꿀 수 있어서 이렇게 드러납니다.
""")


