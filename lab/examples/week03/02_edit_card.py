# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 준비
mine = {
    "아이디": "my_first_card",
    "이름": "나의 첫 카드",
    "비용": 100,
    "즉시효과": {"수율": 5},
}

# %% [2] 값을 고칩니다
mine["비용"] = 80
mine["즉시효과"] = {"수율": 6}       # 효과도 딕셔너리입니다

for key in ("아이디", "이름", "비용", "즉시효과"):
    print(f"{key:<10} {mine.get(key)}")     # .get( ) : 없으면 에러 대신 None

# %% [3] 효과를 두 개로
mine["즉시효과"] = {"수율": 6, "순도": 3}
print(mine["즉시효과"])

# %% [4] 이름표를 더하고 빼기
mine["분류"] = "운전"                 # 없던 이름표를 쓰면 새로 생깁니다
print(list(mine.keys()))
mine.pop("분류", None)                 # 없어도 에러 안 나게 None 을 함께
print(list(mine.keys()))


