# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 카드 세 장 (실제 데이터에서 값만 간추렸습니다)
cards = [
    {"이름": "반응기 온도 상승", "비용": 100},
    {"이름": "고효율 촉매 도입", "비용": 250},
    {"이름": "압력 상승", "비용": 60},
]
for p in cards:
    print(f'{p["이름"]:<16} {p["비용"]:>5}억')

# %% [2] 한 항목만 뽑아 새 리스트 만들기 (리스트 컴프리헨션)
costs = [p["비용"] for p in cards]     # "각 p 에 대해 p['비용'] 을 모아라"
print(costs)

# %% [3] 가장 작은 것 · 큰 것
print("가장 싼 비용  :", min(costs))
print("가장 비싼 비용:", max(costs))

# key= 를 주면 '무엇을 기준으로' 비교할지 정할 수 있습니다
cheapest = min(cards, key=lambda p: p["비용"])   # lambda : 이름 없는 짧은 함수
print(f'가장 싼 카드: {cheapest["이름"]}')

# %% [4] 조건에 맞는 것만 (if 를 뒤에 붙입니다 - 자세한 if 는 4주)
cheap_ones = [p["이름"] for p in cards if p["비용"] <= 100]
print(f"100% 이하: {cheap_ones}")


