# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 중괄호와 "이름표: 값"
one_card = {
    "이름": "예시 카드",       # 이름표 "이름" 에 값 "예시 카드"
    "비용": 100,
    "즉시효과": {"수율": 5},    # 값 자리에 딕셔너리를 또 넣을 수도 있습니다
}
print(one_card)

# %% [2] 이름표로 꺼냅니다
print(one_card["이름"])
print(one_card["비용"], "억")

# %% [3] 안에 있는 딕셔너리도 같은 방법으로
print(one_card["즉시효과"])              # 딕셔너리 통째로
print(one_card["즉시효과"]["수율"])      # 그 안의 값 하나

# %% [4] 이름표만 · 값만 · 둘 다
print(list(one_card.keys()))     # .keys()   : 이름표들
print(list(one_card.values()))   # .values() : 값들
for key, value in one_card.items():  # .items()  : 둘을 짝지어
    print(f"  {key:<8} {value}")


