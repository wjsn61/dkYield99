# %% [0] 준비 - ★ 외우지 마세요. 새 파일에 그대로 복사해 쓰면 됩니다.
#      윈도우에서 한글이 깨지지 않게 하는 것이 전부입니다.
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 대괄호로 묶으면 리스트
indicators = ['예산', '생산량', '수율', '순도', '안전지수']
print(indicators)
print("개수:", len(indicators))     # len( ) : 몇 개인지 세기

# %% [2] 자리 번호로 꺼냅니다 - 0 부터 셉니다 (중요!)
print("0번째 :", indicators[0])     # 첫 번째가 0번
print("1번째 :", indicators[1])
print("맨 뒤  :", indicators[-1])   # -1 은 뒤에서 첫 번째

# %% [3] 잘라내기 (슬라이스)
print(indicators[0:2])              # 0번부터 2번 '앞' 까지 = 0,1
print(indicators[:3])               # 처음부터 3개
print(indicators[2:])               # 2번부터 끝까지

# %% [4] 하나씩 꺼내 보기
for name in indicators:             # 목록의 값을 하나씩 이름에 담아 반복
    print(" -", name)


