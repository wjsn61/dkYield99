import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 게임의 진짜 카드 한 장
#        (파일을 직접 열어 확인해 보세요 - 이런 게 20장 들어 있습니다)

card = {
    "아이디": "reactor_temp_up",
    "이름": "반응기 온도 상승",
    "분류": "운전",
    "비용": 0,
    "즉시효과": {"전환율": +5, "선택도": -3, "에너지비": +3},
    "부작용": {"안전지수": -5, "순도": -2},
}

# %% [2] 이름표 하나씩 뜯어보기
for key, value in card.items():
    print(f"  {key:<8} {value}")

# %% [3] 안쪽까지 파고들기
print("비용     :", card["비용"], "억")
print("즉시효과 :", card["즉시효과"])
print("안전 부작용 :", card["부작용"]["안전지수"])

# %% [4] 카드 여러 장 = 리스트 안에 딕셔너리
cards = [card]              # 지금은 한 장뿐
print(type(cards), type(cards[0]))
print("장 수:", len(cards))
print("첫 장 이름:", cards[0]["이름"])


