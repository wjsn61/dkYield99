import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# %% [1] 같은 계산, 두 가지 표기
values = [80, 78, 81, 77, 83]

print(f"{'엑셀':<18}{'결과':>10}   파이썬")
print("-" * 52)
print(f"{'=AVERAGE(범위)':<18}{sum(values) / len(values):>10.2f}   sum(v)/len(v)")
print(f"{'=MIN(범위)':<18}{min(values):>10.2f}   min(v)")
print(f"{'=MAX(범위)':<18}{max(values):>10.2f}   max(v)")
print(f"{'=COUNT(범위)':<18}{len(values):>10}   len(v)")

# %% [2] 중앙값 - 줄 세워서 가운데
ordered = sorted(values)              # sorted( ) : 작은 것부터 줄 세우기
n = len(ordered)
median_value = ordered[n // 2] if n % 2 else (ordered[n // 2 - 1] + ordered[n // 2]) / 2
#      //  몫만 (정수 나눗셈)      %  나머지 - 홀수면 1, 짝수면 0
print("정렬:", ordered)
print(f"{'=MEDIAN(범위)':<18}{median_value:>10.2f}")

# %% [3] 평균과 중앙값이 다를 때
values2 = [80, 78, 81, 77, 830]     # 하나만 크게 바꿔 봅니다
print("\n한 값이 튀면:")
print(f"  평균   {sum(values2) / len(values2):>8.2f}   ← 크게 끌려갑니다")
print(f"  중앙값 {sorted(values2)[2]:>8.2f}   ← 거의 그대로")

